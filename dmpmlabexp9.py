import pandas as pd
import numpy as np
from mlxtend.preprocessing import TransactionEncoder
from mlxtend.frequent_patterns import apriori
from scipy.stats import chi2_contingency
import warnings

# Suppress Deprecation Warnings to keep output clean
warnings.filterwarnings('ignore', category=DeprecationWarning)

# --- Part 1: Frequent Itemsets Extraction ---
print("=== Task 1: Frequent Itemsets ===\n")
transactions = [
    ['bread', 'milk'],
    ['bread', 'diaper', 'beer', 'eggs'],
    ['milk', 'diaper', 'beer', 'coke'],
    ['bread', 'milk', 'diaper', 'beer'],
    ['bread', 'milk', 'diaper', 'coke']
]

# Create True/False table
te = TransactionEncoder()
te_array = te.fit(transactions).transform(transactions)

df = pd.DataFrame(
    te_array,
    columns=te.columns_,
    index=['T1', 'T2', 'T3', 'T4', 'T5']
)

print("True/False Table:")
print(df)
print()

# Find frequent itemsets
frequent_itemsets = apriori(
    df,
    min_support=0.6,
    use_colnames=True
)

# Add count
frequent_itemsets['count'] = (
    frequent_itemsets['support'] * len(transactions)
).astype(int)

print("Frequent Itemsets:")
print(frequent_itemsets.to_string(index=False))
print("\n" + "="*40 + "\n")

# --- Part 2: Chi-Square Test ---
print("=== Task 2: Chi-Square Independence Test ===\n")
data = np.array([
    [23, 18, 8, 9],
    [15, 6, 12, 10]
])

print("H0: Chocolate flavour is independent of gender")
print("H1: Chocolate flavour is not independent of gender\n")

degrees_of_freedom = (data.shape[0] - 1) * (data.shape[1] - 1)
print("Degrees of freedom:", degrees_of_freedom)

chi2, p, dof, expected = chi2_contingency(data)

print("Expected Frequency Table:")
print(expected)